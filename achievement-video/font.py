GLYPHS = {}
for ch, s in _RAW.items():
    rows = s.split("|")
    GLYPHS[ch] = [[c == "#" for c in r] for r in rows]


def text_width(text, scale=1, spacing=1):
    w = 0
    for i, ch in enumerate(text):
        g = GLYPHS[ch]
        w += len(g[0]) * scale
        if i < len(text) - 1:
            w += spacing * scale
    return w


def glyph_mask(ch, scale=1):
    g = GLYPHS[ch]
    h, w = len(g), len(g[0])
    im = Image.new("L", (w * scale, h * scale), 0)
    px = im.load()
    for y in range(h):
        for x in range(w):
            if g[y][x]:
                for dy in range(scale):
                    for dx in range(scale):
                        px[x * scale + dx, y * scale + dy] = 255
    return im


def text_mask(text, scale=1, spacing=1, bold=False):
    w = text_width(text, scale, spacing) + (scale if bold else 0)
    im = Image.new("L", (max(w, 1), 7 * scale), 0)
    x = 0
    for ch in text:
        m = glyph_mask(ch, scale)
        im.paste(255, (x, 0), m)
        if bold:
            im.paste(255, (x + scale, 0), m)
        x += m.width + spacing * scale + (scale if bold else 0) * 0
    return im


def outlined(mask, fill, outline, thick=1, shadow=None, shadow_off=(1, 1)):
    """Return RGBA image of mask with an outline (and optional drop shadow)."""
    pad = thick + max(abs(shadow_off[0]), abs(shadow_off[1])) if shadow else thick
    W, H = mask.width + pad * 2, mask.height + pad * 2
    out = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    if shadow:
        for dy in range(-thick, thick + 1):
            for dx in range(-thick, thick + 1):
                out.paste(shadow, (pad + dx + shadow_off[0], pad + dy + shadow_off[1]), mask)
    for dy in range(-thick, thick + 1):
        for dx in range(-thick, thick + 1):
            out.paste(outline, (pad + dx, pad + dy), mask)
    out.paste(fill, (pad, pad), mask)
    return out
